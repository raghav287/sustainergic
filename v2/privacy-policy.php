    <!-- Smooth scroll script for TOC -->
    <script>
        document.querySelectorAll('.legal-toc-link').forEach(link => {
            link.addEventListener('click', function(e) {
                e.preventDefault();
                const targetId = this.getAttribute('href');
                if (targetId && targetId.startsWith('#')) {
                    const targetEl = document.querySelector(targetId);
                    if (targetEl) {
                        const offset = window.innerWidth <= 991 ? 140 : 110;
                        const targetPosition = targetEl.getBoundingClientRect().top + window.pageYOffset - offset;
                        
                        window.scrollTo({
                            top: targetPosition,
                            behavior: 'smooth'
                        });

                        document.querySelectorAll('.legal-toc-link').forEach(l => l.classList.remove('active'));
                        this.classList.add('active');

                        if (window.innerWidth <= 991) {
                            this.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
                        }
                    }
                }
            });
        });

        // Highlight TOC link on scroll & auto-scroll pill bar on mobile
        let isTicking = false;
        window.addEventListener('scroll', () => {
            if (!isTicking) {
                window.requestAnimationFrame(() => {
                    const cards = document.querySelectorAll('.legal-card');
                    const scrollPosition = window.scrollY + (window.innerWidth <= 991 ? 160 : 130);
                    let currentId = '';

                    cards.forEach(card => {
                        if (scrollPosition >= card.offsetTop) {
                            currentId = card.getAttribute('id');
                        }
                    });

                    if (currentId) {
                        document.querySelectorAll('.legal-toc-link').forEach(link => {
                            const isMatch = link.getAttribute('href') === '#' + currentId;
                            if (isMatch && !link.classList.contains('active')) {
                                document.querySelectorAll('.legal-toc-link').forEach(l => l.classList.remove('active'));
                                link.classList.add('active');
                                if (window.innerWidth <= 991) {
                                    link.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
                                }
                            }
                        });
                    }
                    isTicking = false;
                });
                isTicking = true;
            }
        });
    </script>
