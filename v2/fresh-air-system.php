                    </div>
                    <h3>DOAS (Dedicated Outdoor Air Systems)</h3>
                    <p>
                        Specialized air handling units that condition 100% outdoor fresh air independently of internal space cooling. Handles 100% of the building's moisture/latent load, ensuring dry, comfortable indoor air.
                    </p>
                </div>

                <!-- 2. ERV & HRV -->
                <div class="gb-service-card">
                    <div class="gb-card-icon-wrapper">
                        <i class="fa-solid fa-arrows-rotate"></i>
                    </div>
                    <h3>Energy Recovery Ventilators (ERV / HRV)</h3>
                    <p>
                        High-efficiency enthalpy wheels and counter-flow heat exchangers that transfer thermal heat and moisture between exhaust air and fresh intake air, reducing cooling plant load by up to 30%.
                    </p>
                </div>

                <!-- 3. Demand-Controlled Ventilation -->
                <div class="gb-service-card">
                    <div class="gb-card-icon-wrapper">
                        <i class="fa-solid fa-gauge"></i>
                    </div>
                    <h3>Demand-Controlled Ventilation (DCV)</h3>
                    <p>
                        Smart ventilation damper controls linked to room CO₂ sensors. Automatically ramps up fresh air during high occupancy (meetings/events) and throttles back during low occupancy to save energy.
                    </p>
                </div>

                <!-- 4. Positive Pressure Clean Air -->
                <div class="gb-service-card">
                    <div class="gb-card-icon-wrapper">
                        <i class="fa-solid fa-shield-virus"></i>
                    </div>
                    <h3>Positive Pressure Filtration Systems</h3>
                    <p>
                        Maintains positive indoor static pressure to block raw outdoor smog, ambient dust, and unconditioned hot air from infiltrating through doors, windows, and facade gaps.
                    </p>
                </div>
            </div>
        </div>
    </section>

