                    </p>
                </div>

                <!-- 3. TABS -->
                <div class="gb-service-card">
                    <div class="gb-card-icon-wrapper">
                        <i class="fa-solid fa-building-user"></i>
                    </div>
                    <h3>TABS (Thermally Activated Building Systems)</h3>
                    <p>
                        Utilizes structural concrete ceilings and floors as thermal energy storage. Chilled or heated water circulates through structural slabs during off-peak power hours, drastically reducing daytime peak electrical demand and chiller capacity.
                    </p>
                </div>

                <!-- 4. Wall-Integrated Radiant Panels -->
                <div class="gb-service-card">
                    <div class="gb-card-icon-wrapper">
                        <i class="fa-solid fa-border-all"></i>
                    </div>
                    <h3>Radiant Wall Systems</h3>
                    <p>
                        Hydronic piping integrated into interior wall plaster or drywall panel modules. Excellent for supplemental perimeter heating/cooling, heritage building retrofits, and cleanrooms requiring strict acoustic and air velocity limits.
                    </p>
                </div>
            </div>
